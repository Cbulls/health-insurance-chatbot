def hira_age_band(ui_band: str | None) -> str | None:
    """UI 연령 → HIRA 캐시 10년 키. 미지 코드는 None."""
    if not ui_band:
        return None
    return _HIRA_FOLD.get(ui_band)


def kosis_ages(ui_band: str | None, table: str = "default") -> list[str] | None:
    """UI 연령 → KOSIS 5세 라벨 목록."""
    if not ui_band:
        return None
    if table == "a054":
        return AGE_BAND_TO_KOSIS_A054.get(ui_band)
    if table == "a0611":
        return AGE_BAND_TO_KOSIS_A0611.get(ui_band)
    return AGE_BAND_TO_KOSIS.get(ui_band)


def age_ui_label(ui_band: str | None) -> str:
    if not ui_band:
        return ""
    return AGE_UI_LABELS.get(ui_band, ui_band)
